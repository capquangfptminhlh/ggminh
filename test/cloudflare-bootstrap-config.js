'use strict';
const assert=require('node:assert/strict');
const {build,ROUTE,TRIGGER}=require('../tools/cloudflare-config-builder');
const id='12345678-1234-4123-8123-123456789abc';
const live=build({mode:'production',databaseId:id});
assert(live.includes(ROUTE));
assert(live.includes(TRIGGER));
assert(live.includes('preview_urls = false'));
assert(live.includes('workers_dev = false'));
assert(live.includes('database_id = "'+id+'"'));
assert(!live.includes('REPLACE_WITH_D1_DATABASE_UUID'));
const privateWorker=build({mode:'bootstrap',databaseId:id});
assert(!privateWorker.includes('[[routes]]'));
assert(!privateWorker.includes('[triggers]'));
assert(!privateWorker.includes('pattern = "browser.lhmcrm.com"'));
assert(privateWorker.includes('preview_urls = false'));
assert(privateWorker.includes('workers_dev = false'));
assert(privateWorker.includes('database_id = "'+id+'"'));
assert(!privateWorker.includes('LHM_LICENSE_ADMIN_TOKEN ='));
assert.throws(()=>build({mode:'unknown',databaseId:id}),/mode/);
assert.throws(()=>build({mode:'production',databaseId:'REPLACE_WITH_D1_DATABASE_UUID'}),/UUID/);
assert.throws(()=>build({mode:'production',databaseId:id,template:'unexpected'}),/template/);
console.log('Cloudflare bootstrap/production configuration, private-route guard and UUID validation PASS');
