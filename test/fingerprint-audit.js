const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { inspectFingerprint } = require('../src/privacy/fingerprintAudit');
const { generateFingerprint } = require('../src/engine/fingerprint');
const { createLaunchArgs } = require('../src/engine/launchArgs');
const { generateExtension } = require('../src/engine/extensionGenerator');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'lhm-fp-audit-'));
try {
  const fp=generateFingerprint({ mode:'native' });
  assert.strictEqual(fp.mode,'native');
  assert.strictEqual(fp.userAgent,'');
  assert.strictEqual(fp.canvasNoiseSeed,0);
  assert.strictEqual(fp.audioNoiseSeed,0);
  const report=inspectFingerprint({engine:'chromium',fingerprint:fp});
  assert.strictEqual(report.mode,'native');
  assert.strictEqual(report.warningCount,0);
  const args=createLaunchArgs({engine:'chromium',profileDir:dir,url:'https://example.org',fingerprint:fp});
  assert(!args.some(s=>s.startsWith('--user-agent=')));
  assert(!args.some(s=>s.startsWith('--load-extension=')));
  const experimental=generateFingerprint({os:'macOS'});
  experimental.webgl.renderer='ANGLE NVIDIA Direct3D11';
  const diagnostic=inspectFingerprint({engine:'chromium',fingerprint:experimental});
  assert(diagnostic.issues.some(x=>x.code==='webgl_os'));
  assert(diagnostic.issues.some(x=>x.code==='canvas_modified'));
  assert(diagnostic.issues.some(x=>x.code==='ua_old'));
  const nativeGecko=inspectFingerprint({engine:'gecko',fingerprint:experimental});
  assert.strictEqual(nativeGecko.mode,'native');
  const profile={id:'pb_fpunit',fingerprint:{mode:'custom', canvasNoiseSeed:0,audioNoiseSeed:0}};
  generateExtension(profile,path.join(dir,'extension-off'));
  let code=fs.readFileSync(path.join(dir,'extension-off','stealth.js'),'utf8');
  assert(code.includes('if (false) try {\\n    const seed = 0;'));
  assert(code.includes('if (false) try {\\n    const audioSeed = 0;'));
  generateExtension({id:'pb_fpunit',fingerprint:{canvasNoiseSeed:17,audioNoiseSeed:5}},path.join(dir,'extension-on'));
  code=fs.readFileSync(path.join(dir,'extension-on','stealth.js'),'utf8');
  assert(code.includes('if (true) try {\\n    const seed = 17;'));
  assert(code.includes('if (true) try {\\n    const audioSeed = 5;'));
  console.log('Fingerprint mode, Canvas OFF/ON and transparent diagnostics tests passed');
}finally{fs.rmSync(dir,{recursive:true,force:true});}
