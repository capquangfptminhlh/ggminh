'use strict';
const assert=require('node:assert/strict'),path=require('node:path'),fs=require('node:fs'),os=require('node:os'),crypto=require('node:crypto'),cp=require('node:child_process');
const {pinnedBaseFor508}=require('../src/engine/camoufoxVersionedBase');
const {installPinnedTree}=require('../src/engine/camoufoxPinnedInstall');
const {signedPayload,sha256File}=require('../src/engine/bundledEngineManager');
const root=path.resolve('synthetic-data-root');
assert.match(fs.readFileSync(path.join(__dirname,'..','main.js'),'utf8'),/const pinnedBase=pinnedBaseFor508\(storageDir\)/);
assert.equal(pinnedBaseFor508(root),path.join(root,'engines-pinned-clean508'));
assert.notEqual(pinnedBaseFor508(root),path.join(root,'engines-pinned'));
assert.throws(()=>pinnedBaseFor508('relative/path'),/absolute/i);
const sandbox=fs.mkdtempSync(path.join(os.tmpdir(),'lhm-versioned-base-'));
const old=path.join(sandbox,'engines-pinned','camoufox'),profile=path.join(sandbox,'profiles','p1'),source=path.join(sandbox,'source');
fs.mkdirSync(old,{recursive:true});fs.mkdirSync(profile,{recursive:true});fs.mkdirSync(source);
fs.writeFileSync(path.join(old,'old-marker'),'old');fs.writeFileSync(path.join(profile,'profile-marker'),'profile');
fs.writeFileSync(path.join(source,'camoufox.exe'),'new');
const manifest={schema:1,engine:'camoufox',version:'156.0.1',entry:'camoufox.exe',files:[{path:'camoufox.exe',...sha256File(path.join(source,'camoufox.exe'))}]};
const pin=crypto.createHash('sha256').update(signedPayload(manifest)).digest('hex');
const next=pinnedBaseFor508(sandbox);fs.mkdirSync(next);
installPinnedTree({source,base:next,manifest,expectedPayloadSha256:pin});
assert.equal(fs.readFileSync(path.join(old,'old-marker'),'utf8'),'old');
assert.equal(fs.readFileSync(path.join(profile,'profile-marker'),'utf8'),'profile');
assert.equal(fs.readFileSync(path.join(next,'camoufox','camoufox.exe'),'utf8'),'new');
assert.throws(()=>installPinnedTree({source,base:next,manifest,expectedPayloadSha256:pin}),/already exists/i);
const interrupted=path.join(sandbox,'interrupted');fs.mkdirSync(interrupted);
const interruptedOld=path.join(interrupted,'engines-pinned','camoufox');fs.mkdirSync(interruptedOld,{recursive:true});
fs.writeFileSync(path.join(interruptedOld,'old-marker'),'old');
const interruptedNext=pinnedBaseFor508(interrupted);fs.mkdirSync(interruptedNext);
const modulePath=require.resolve('../src/engine/camoufoxPinnedInstall');
const child=`const fs=require('fs');const {installPinnedTree}=require(${JSON.stringify(modulePath)});fs.renameSync=()=>process.exit(79);installPinnedTree(${JSON.stringify({source,base:interruptedNext,manifest,expectedPayloadSha256:pin})})`;
const result=cp.spawnSync(process.execPath,['-e',child],{encoding:'utf8'});
assert.equal(result.status,79,'child must stop during new engine promotion');
assert.equal(fs.readFileSync(path.join(interruptedOld,'old-marker'),'utf8'),'old');
assert.equal(fs.existsSync(path.join(interruptedNext,'camoufox')),false);
console.log('508 engine uses a distinct installation base: PASS');
