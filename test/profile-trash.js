'use strict';
const assert=require('assert'),fs=require('fs'),os=require('os'),path=require('path');
const Store=require('../src/db/store');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'lhm-trash-'));
const DAY=86400000;
try {
  const store=new Store(root);
  const now=Date.parse('2026-10-20T00:00:00Z');
  const a=store.saveProfile({name:'Production profile',engine:'gecko',tags:['Important']});
  const chromiumDir=path.join(root,'profiles',a.id);
  const geckoDir=path.join(root,'gecko-profiles',a.id);
  fs.mkdirSync(chromiumDir,{recursive:true});
  fs.mkdirSync(geckoDir,{recursive:true});
  fs.writeFileSync(path.join(chromiumDir,'sample-cookie.db'),'retain-this-file');
  fs.writeFileSync(path.join(geckoDir,'session.txt'),'retain-this-firefox-file');
  assert.strictEqual(store.trashProfile(a.id,now),true);
  assert.strictEqual(store.getProfile(a.id),undefined);
  assert.strictEqual(store.getTrashedProfiles().length,1);
  assert(fs.existsSync(path.join(chromiumDir,'sample-cookie.db')));
  assert(fs.existsSync(path.join(geckoDir,'session.txt')));
  assert.strictEqual(new Store(root).getTrashedProfiles()[0].name,'Production profile');
  assert.throws(()=>store.saveProfile({id:a.id,name:'Accidental reuse'}),/reserved/);
  const back=store.restoreTrashedProfile(a.id,now+20*DAY);
  assert.strictEqual(back.id,a.id);
  assert.strictEqual(back.engine,'gecko');
  assert.deepStrictEqual(back.tags,['Important']);
  assert(fs.existsSync(path.join(geckoDir,'session.txt')));
  assert.strictEqual(store.getTrashedProfiles().length,0);
  assert.strictEqual(store.trashProfile(a.id,now),true);
  assert.throws(()=>store.restoreTrashedProfile(a.id,now+30*DAY),/expired/);
  assert.strictEqual(store.purgeExpiredTrashedProfiles(now+29*DAY).purged,0);
  assert.strictEqual(store.purgeExpiredTrashedProfiles(now+31*DAY).purged,1);
  assert.strictEqual(store.getTrashedProfiles().length,0);
  assert.strictEqual(fs.existsSync(chromiumDir),false);
  assert.strictEqual(fs.existsSync(geckoDir),false);
  const b=store.saveProfile({name:'Pending'});
  store.trashProfile(b.id,now);
  const baseline=fs.readFileSync(store.dbFile,'utf8');
  const real=store.saveData;
  store.saveData=()=>{throw Error('TEST_DISK_FULL')};
  assert.throws(()=>store.restoreTrashedProfile(b.id,now+DAY),/TEST_DISK_FULL/);
  assert.strictEqual(store.getTrashedProfiles().length,1);
  assert.throws(()=>store.purgeTrashedProfile(b.id),/TEST_DISK_FULL/);
  assert.strictEqual(store.getTrashedProfiles().length,1);
  assert.strictEqual(fs.readFileSync(store.dbFile,'utf8'),baseline);
  store.saveData=real;
  assert(store.purgeTrashedProfile(b.id));
  assert.strictEqual(new Store(root).getTrashedProfiles().length,0);
  assert.strictEqual(store.purgeTrashedProfile(b.id),false);
  const html=fs.readFileSync(path.join(__dirname,'../src/ui/index.html'),'utf8');
  const script=fs.readFileSync(path.join(__dirname,'../src/ui/profileTrash.js'),'utf8');
  for(const id of ['btn-trash-profiles','modal-profile-trash','trash-profile-list','trash-dialog-expired'])
    assert(html.includes('id="'+id+'"'));
  assert(script.includes('window.api.restoreTrashedProfile('));
  console.log('v3.6 trash retention, session preservation, restore, permanent purge and rollback passed');
}finally{fs.rmSync(root,{recursive:true,force:true});}